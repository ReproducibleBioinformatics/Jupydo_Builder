#!/usr/bin/env bash
# Regenerates the Python lock from lists/python-requirements.in: every dependency
# resolved to an exact version, with hashes. Run it only when you want to update the
# Python stack (then rebuild the bundles and publish them).
# Uses the same portable Python as the bundles, so the resolution is the same.
#
#   scripts/lock-python.sh                  lists/python-requirements.lock (current)
#   VARIANT=legacy scripts/lock-python.sh   lists/python-requirements-legacy.lock:
#       resolved INSIDE ubuntu:16.04 with binary packages only, so every package gets
#       the newest version that has a wheel for glibc 2.23 (the legacy bundle). The
#       pinned requirements (e.g. jupyterhub==5.5.1) stay the same.
set -euo pipefail
cd "$(dirname "$0")/.."
ROOT="$(pwd)"
mkdir -p vendor/.downloads
HEADER='# Generated by scripts/lock-python.sh from python-requirements.in: do not edit by hand.\n# Every package pinned to an exact version, with the hashes of its files.'

if [ "${VARIANT:-current}" = legacy ]; then
  OUT=lists/python-requirements-legacy.lock
  scripts/lib/python-standalone.sh x86_64 vendor/.downloads/python-standalone-x86_64.tar.gz
  docker run --rm --platform linux/amd64 -v "${ROOT}:/b" -w /b \
    -e HOST_UID="$(id -u)" -e HOST_GID="$(id -g)" ubuntu:16.04 bash -c '
      set -euo pipefail
      apt-get update -qq && apt-get install -y -qq --no-install-recommends ca-certificates > /dev/null
      tar -xzf vendor/.downloads/python-standalone-x86_64.tar.gz -C /tmp
      /tmp/python/bin/python3 -m pip install --quiet --disable-pip-version-check pip-tools
      /tmp/python/bin/pip-compile --quiet --generate-hashes --allow-unsafe --strip-extras \
        --no-emit-index-url --no-header --pip-args "--only-binary=:all:" \
        -o lists/python-requirements-legacy.lock lists/python-requirements.in
      chown "${HOST_UID}:${HOST_GID}" lists/python-requirements-legacy.lock'
  sed -i "1i ${HEADER}\n# LEGACY: resolved on ubuntu:16.04 (glibc 2.23), binary packages only." "$OUT"
else
  OUT=lists/python-requirements.lock
  work="$(mktemp -d)"; trap 'rm -rf "$work"' EXIT
  arch="$(uname -m)"
  scripts/lib/python-standalone.sh "$arch" "$work/python.tar.gz"
  tar -xzf "$work/python.tar.gz" -C "$work"
  "$work/python/bin/python3" -m pip install --quiet pip-tools
  "$work/python/bin/pip-compile" --quiet --generate-hashes --allow-unsafe --strip-extras \
    --no-emit-index-url --no-header -o "$OUT" lists/python-requirements.in
  sed -i "1i ${HEADER}" "$OUT"
fi
echo "Lock updated: $OUT, $(grep -cE '^[A-Za-z0-9_.-]+==' "$OUT") packages"
grep -E '^(jupyterhub|jupyterlab|notebook|ipykernel)==' "$OUT" | sed 's/ .*//'
